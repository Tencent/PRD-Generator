def W(key, lang=None):
    """Vocabulary entry for the given (or current) language."""
    use = (normalize(lang) or _cur) if lang is not None else _cur
    return WORDS[use][key]


_RE_CACHE = {}


def section_re():
    """Matches "<Page Interaction> — <page name>" headings, capturing the page name."""
    key = ("section", _cur)
    if key not in _RE_CACHE:
        _RE_CACHE[key] = re.compile(re.escape(W("sec_page")) + r"\s*[—–-]\s*(.+)$")
    return _RE_CACHE[key]


def section_probe_re():
    """Same as section_re but only needs *some* text after the dash (used where the name is not captured)."""
    key = ("probe", _cur)
    if key not in _RE_CACHE:
        _RE_CACHE[key] = re.compile(re.escape(W("sec_page")) + r"\s*[—–-]\s*\S")
    return _RE_CACHE[key]


def note_re():
    key = ("note", _cur)
    if key not in _RE_CACHE:
        _RE_CACHE[key] = re.compile(W("note_re"))
    return _RE_CACHE[key]


def label_limit():
    """流程图连线标签的建议最大长度：中文 14 字；英文单词更长，放宽到 28 个字符。"""
    return 28 if _cur == "en" else 14


def appendix_b_match(title):
    return re.match(W("appendix_b_re"), title)
