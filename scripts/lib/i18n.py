"""i18n: language dimension for prdkit (zh = default, en).

Design rules (read before editing):
  1. The language of a project lives in spec/screens.json -> "lang" ("zh" | "en"). Missing = "zh",
     so every pre-existing project behaves exactly as before.
  2. The Chinese strings in the code base are the source of truth and are never rewritten.
     English text is added NEXT to them:  t("中文", "English")  /  Issue(..., en="English").
  3. Words that the checkers rely on to recognise the PRD structure (section titles, the "Flow" line, ...)
     live in WORDS below, one entry per language. The zh entries must stay byte-identical to the literals
     that used to be hard-coded in lint.py / links.py / flow.py.
  4. regress.py compares zh output byte-for-byte against a pre-i18n baseline.

中文说明：项目语言写在 spec.lang，缺省 zh，旧项目行为不变；中文原文不改，英文并排加；
结构识别用词集中在 WORDS，zh 值必须与历史写死的字面量逐字一致。
"""
import os
import re

DEFAULT = "zh"
LANGS = ("zh", "en")

_ALIASES = {
    "": DEFAULT, "zh": "zh", "zh-cn": "zh", "zh_cn": "zh", "zh-hans": "zh", "cn": "zh", "chinese": "zh",
    "en": "en", "en-us": "en", "en_us": "en", "en-gb": "en", "english": "en",
}

_cur = DEFAULT


def normalize(value):
    """Return "zh" / "en", or None when the value is not a supported language."""
    return _ALIASES.get(str(value if value is not None else "").strip().lower())


def set_lang(value):
    global _cur
    _cur = normalize(value) or DEFAULT
    return _cur


def cur():
    return _cur


def from_env():
    """Initial language for commands that run before any project exists (doctor / setup / init)."""
    return normalize(os.environ.get("PRDKIT_LANG")) or DEFAULT


def lang_of(data):
    """Language recorded in a parsed screens.json (missing or invalid = zh)."""
    if isinstance(data, dict):
        return normalize(data.get("lang")) or DEFAULT
    return DEFAULT


def t(zh, en=None):
    """Pick the message for the current language. Without an English text the Chinese one is used."""
    return en if (_cur == "en" and en is not None) else zh


